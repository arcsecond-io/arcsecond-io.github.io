import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const docsDir = join(here, '..')

// ---------------------------------------------------------------------------
// Where the site is served from. The public site lives at the root of
// docs.arcsecond.io; the copy bundled into the Arcsecond.local web image is
// served by its nginx under /docs/ (`npm run docs:build:embedded`).
// ---------------------------------------------------------------------------
const base = process.env.DOCS_BASE || '/'

// ---------------------------------------------------------------------------
// Visibility. Every page declares who may see it in its frontmatter:
//   public    — docs.arcsecond.io
//   embedded  — the copy inside a self-hosted installation (the default)
//   internal  — never leaves the source repository
// A build has a flavour (DOCS_VISIBILITY, `public` by default) and excludes
// every page above it. A page is therefore public only in writing, and a page
// without frontmatter is embedded, not public.
//
// TODO(visibility): the REST reference, once generated, needs the list of the
// apps whose endpoints stay embedded-only. Name them here when that lands.
// ---------------------------------------------------------------------------
const RANK = { public: 0, embedded: 1, internal: 2 }
const flavour = process.env.DOCS_VISIBILITY || 'public'
if (!(flavour in RANK)) throw new Error(`DOCS_VISIBILITY must be one of ${Object.keys(RANK)}, got ${flavour}`)

function* markdownFiles (dir) {
  for (const name of readdirSync(dir)) {
    if (name === '.vitepress' || name === 'node_modules' || name === 'public') continue
    const path = join(dir, name)
    if (statSync(path).isDirectory()) yield* markdownFiles(path)
    else if (name.endsWith('.md')) yield path
  }
}

function visibilityOf (file) {
  const text = readFileSync(file, 'utf8')
  if (!text.startsWith('---\n')) return 'embedded'
  const end = text.indexOf('\n---', 4)
  const head = end === -1 ? '' : text.slice(4, end)
  const match = head.match(/^visibility:\s*(\S+)/m)
  return match ? match[1] : 'embedded'
}

// docs/index.md is the home page: always in.
const excluded = []
for (const file of markdownFiles(docsDir)) {
  const rel = relative(docsDir, file)
  if (rel === 'index.md') continue
  if (RANK[visibilityOf(file)] > RANK[flavour]) excluded.push(rel)
}
const excludedUrls = excluded.map(rel => '/' + rel.replace(/\.md$/, '').replace(/\/index$/, '/'))

// ---------------------------------------------------------------------------
// The command reference is generated by the tool itself (`arcsecond docs
// commands --out docs/reference/commands`), one page per command, and this
// manifest with them. The sidebar reads it, so a command added to or removed
// from the tool changes the navigation without anyone editing this file.
// ---------------------------------------------------------------------------
const commands = JSON.parse(readFileSync(join(here, '../reference/commands/commands.json'), 'utf8'))
const commandItems = commands.commands.map(c => ({ text: `arcsecond ${c.name}`, link: `/reference/commands/${c.name}.md` }))

// ---------------------------------------------------------------------------
// Old addresses. The site was restructured in September 2026 (Start / Guides /
// Reference / Concepts); every address it had before answers with a page that
// sends the browser on. GitHub Pages cannot redirect, so these are files
// written at the end of the build — see buildEnd. The Arcsecond.local .env
// comments and the app's help links still name some of the old addresses.
// ---------------------------------------------------------------------------
const redirects = JSON.parse(readFileSync(join(here, 'redirects.json'), 'utf8'))
// The command pages moved as a folder; one redirect per command, from the
// manifest, so a command added later is covered without editing anything.
for (const c of commands.commands) redirects[`/cli/commands/${c.name}`] = `/reference/commands/${c.name}`

function redirectPage (target) {
  const safe = target.replace(/"/g, '&quot;')
  return `<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">
<title>Moved</title><meta name="robots" content="noindex">
<meta http-equiv="refresh" content="0; url=${safe}"><link rel="canonical" href="${safe}">
<script>location.replace(${JSON.stringify(target)})</script></head>
<body><p>This page has moved to <a href="${safe}">${safe}</a>.</p></body></html>\n`
}

