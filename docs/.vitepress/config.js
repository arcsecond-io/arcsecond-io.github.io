  buildEnd (siteConfig) {
    const outDir = siteConfig.outDir
    // 1. Every old address answers.
    for (const [from, to] of Object.entries(redirects)) {
      const target = to.startsWith('http') ? to : base.replace(/\/$/, '') + to
      const file = join(outDir, from.endsWith('/') ? from + 'index.html' : from + '.html')
      mkdirSync(dirname(file), { recursive: true })
      if (existsSync(file)) throw new Error(`redirect ${from} would overwrite a real page`)
      writeFileSync(file, redirectPage(target))
    }
    // 2. Nothing in this build links to a page this flavour excludes.
    const offenders = []
    const walk = dir => {
      for (const name of readdirSync(dir)) {
        const path = join(dir, name)
        if (statSync(path).isDirectory()) walk(path)
        else if (name.endsWith('.html')) {
          const html = readFileSync(path, 'utf8')
          for (const url of excludedUrls) {
            const href = base.replace(/\/$/, '') + url
            if (html.includes(`href="${href}"`) || html.includes(`href="${href}.html"`)) offenders.push(`${relative(outDir, path)} → ${url}`)
          }
        }
      }
    }
    walk(outDir)
    if (offenders.length) throw new Error(`a ${flavour} page links to a page this flavour excludes:\n  ` + offenders.join('\n  '))
    console.log(`docs: flavour ${flavour}, ${excluded.length} page(s) excluded, ${Object.keys(redirects).length} redirect(s) written`)
  },

